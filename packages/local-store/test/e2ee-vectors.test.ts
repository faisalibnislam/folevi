// E2EE test vectors (docs/E2EE_DESIGN.md §4.10, fixtures/e2ee-vectors.json). Every vector is recomputed on
// the WebCrypto backend and on the noble backend and must match the fixture byte for byte; every envelope in
// the fixture must open on both; and the formats are checked once more against node:crypto, so the fixture
// is plain standard HKDF / AES-256-GCM / X25519 / Ed25519 / SHA-256. UPDATE_GOLDEN=1 regenerates the fixture.
import {
  createDecipheriv,
  createHash,
  createHmac,
  createPrivateKey,
  createPublicKey,
  diffieHellman,
  hkdfSync,
  verify as nodeVerify,
} from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { inflateRawSync } from "node:zlib";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { concatBytes, fromHex, toHex, utf8 } from "../src/bytes";
import {
  cryptoBackend,
  forceBackend,
  fromBase64Url,
  importAead,
  openFileStream,
  openFileStreamRange,
  openRecord,
  openSealed,
  openStatement,
  parseRecoveryKey,
  recordKeyVersion,
  verifyStatement,
  x25519FromSeed,
  type BackendName,
} from "../src/crypto/e2ee";
import { computeVectors, pattern, type Vectors } from "./e2ee-helpers";

const fixturePath = resolve(__dirname, "../fixtures/e2ee-vectors.json");
const update = process.env.UPDATE_GOLDEN === "1";
const BACKENDS: BackendName[] = ["webcrypto", "noble"];

afterAll(() => forceBackend(null));

function load(): Vectors {
  return JSON.parse(readFileSync(fixturePath, "utf8")) as Vectors;
}

describe("e2ee vectors", () => {
  it("node 22 has WebCrypto X25519, Ed25519 and AES (so the webcrypto backend is real here)", async () => {
    forceBackend(null);
    expect(await cryptoBackend()).toEqual({ x25519: "webcrypto", ed25519: "webcrypto", aes: "webcrypto" });
  });

  for (const backend of BACKENDS) {
    it(`${backend}: recomputes every vector`, async () => {
      forceBackend(backend);
      const computed = await computeVectors();
      if (update && backend === "webcrypto") {
        const out = {
          $description:
            "Folevi end-to-end encryption vectors (docs/E2EE_DESIGN.md §4.10). Generated by UPDATE_GOLDEN=1 vitest run test/e2ee-vectors.test.ts; every implementation must reproduce them.",
          ...computed,
        };
        writeFileSync(fixturePath, JSON.stringify(out, null, 2) + "\n");
      }
      const { $description: _d, ...fixture } = load();
      expect(computed).toEqual(fixture);
    });

    it(`${backend}: opens every envelope in the fixture`, async () => {
      forceBackend(backend);
      const v = load();
      for (const r of v.records) {
        const env = fromHex(r.envelopeHex);
        expect(recordKeyVersion(env)).toBe(r.keyVersion);
        const opened = await openRecord(await importAead(fromHex(r.keyHex)), r.context, env);
        expect(toHex(opened), r.name).toBe(r.plaintextHex);
        // The key-picker form gets the header's version.
        const seen: number[] = [];
        await openRecord(
          async (version) => {
            seen.push(version);
            return importAead(fromHex(r.keyHex));
          },
          r.context,
          env,
        );
        expect(seen).toEqual([r.keyVersion]);
      }
      const fileKey = await importAead(fromHex(v.streams[0]!.keyHex));
      for (const s of v.streams) {
        const plain = pattern(s.length);
        // Envelopes over 1 byte are stored by hash; the recompute test pins them, here they are resealed.
        if (s.envelopeHex) {
          expect(toHex(await openFileStream(fileKey, s.context, fromHex(s.envelopeHex)))).toBe(toHex(plain));
        }
      }
      expect(
        toHex(await openFileStream(fileKey, v.streams[0]!.context, fromHex(v.smallChunkStream.envelopeHex))),
      ).toBe(toHex(pattern(40)));
      for (const b of v.boxes) {
        const recipient = await x25519FromSeed(fromHex(b.recipientSeedHex));
        expect(toHex(recipient.publicKey)).toBe(b.recipientPubHex);
        const opened = await openSealed(recipient.privateKey, recipient.publicKey, b.context, fromHex(b.boxHex));
        expect(toHex(opened), b.name).toBe(b.plaintextHex);
      }
      for (const s of v.statements) {
        const pub = fromHex(s.signerPubHex);
        expect(await verifyStatement(pub, s)).toBe(true);
        expect(await openStatement(pub, s)).toEqual(JSON.parse(s.body));
      }
      for (const p of v.recoveryParse) {
        const parsed = parseRecoveryKey(p.input);
        expect(parsed ? toHex(parsed) : null, p.input).toBe(p.bytesHex);
      }
    });
  }

  it("the stream vectors reseal to the pinned envelopes and ranges", async () => {
    // (Covered by the recompute test; this one also reads every stored range.)
    for (const backend of BACKENDS) {
      forceBackend(backend);
      const v = load();
      const { sealFileStream } = await import("../src/crypto/e2ee");
      const key = await importAead(fromHex(v.streams[0]!.keyHex));
      for (const s of v.streams) {
        const env = await sealFileStream(key, s.context, pattern(s.length), { noncePrefix: fromHex(s.noncePrefixHex) });
        expect(createHash("sha256").update(env).digest("hex")).toBe(s.envelopeSha256);
        for (const r of s.ranges) {
          expect(toHex(await openFileStreamRange(key, s.context, env, r.start, r.end))).toBe(r.plaintextHex);
        }
      }
    }
  });
});

describe("e2ee vectors are standard primitives (node:crypto)", () => {
  let v: Vectors;
  beforeAll(() => {
    v = load();
  });
  const SALT = Buffer.from("folevi/e2ee/v1");

  it("HKDF-SHA256 rows", () => {
    for (const row of v.hkdf) {
      const out = Buffer.from(hkdfSync("sha256", fromHex(row.ikmHex), SALT, row.info, 32));
      expect(out.toString("hex"), row.info).toBe(row.okmHex);
    }
    const okm = (info: string) => v.hkdf.find((r) => r.info === info)!.okmHex;
    expect(v.derived.amkCheckHex).toBe(okm("account/check").slice(0, 32));
    expect(v.derived.skCheckHex).toBe(okm("space/check").slice(0, 32));
  });

  it("FLV1 0x03 records decrypt with plain AES-256-GCM and AAD = header ‖ context", () => {
    for (const r of v.records) {
      const env = fromHex(r.envelopeHex);
      const header = env.subarray(0, 22);
      expect(toHex(header.subarray(0, 5))).toBe("464c563103");
      const d = createDecipheriv("aes-256-gcm", fromHex(r.keyHex), env.subarray(10, 22));
      d.setAAD(concatBytes(header, utf8(r.context)));
      d.setAuthTag(env.subarray(env.length - 16));
      let plain = Buffer.concat([d.update(env.subarray(22, env.length - 16)), d.final()]);
      if (header[5] === 1) plain = inflateRawSync(plain);
      expect(plain.toString("hex"), r.name).toBe(r.plaintextHex);
    }
    expect(v.records.find((r) => r.name === "compressed")!.envelopeHex.slice(10, 12)).toBe("01");
    expect(v.records.find((r) => r.name === "compressible but compress:false")!.envelopeHex.slice(10, 12)).toBe("00");
    expect(v.records.find((r) => r.name === "incompressible 2 KiB")!.envelopeHex.slice(10, 12)).toBe("00");
  });

  it("FLV1 0x04 streams decrypt chunk by chunk with plain AES-256-GCM", () => {
    for (const s of v.streams.filter((x) => x.envelopeHex)) {
      const env = fromHex(s.envelopeHex!);
      const h = env.subarray(0, 17);
      const nonce = concatBytes(h.subarray(9, 17), new Uint8Array(4));
      const d = createDecipheriv("aes-256-gcm", fromHex(s.keyHex), nonce);
      d.setAAD(concatBytes(h, utf8(s.context), new Uint8Array([1])));
      d.setAuthTag(env.subarray(env.length - 16));
      const plain = Buffer.concat([d.update(env.subarray(17, env.length - 16)), d.final()]);
      expect(plain.toString("hex")).toBe(toHex(pattern(s.length)));
    }
  });

  it("FLS1 boxes: X25519 shared secret, HKDF with salt E ‖ R, AES-256-GCM", () => {
    const pkcs8 = (seed: Uint8Array) =>
      createPrivateKey({ key: Buffer.concat([Buffer.from("302e020100300506032b656e04220420", "hex"), seed]), format: "der", type: "pkcs8" });
    const spki = (pub: Uint8Array) =>
      createPublicKey({ key: Buffer.concat([Buffer.from("302a300506032b656e032100", "hex"), pub]), format: "der", type: "spki" });
    for (const b of v.boxes) {
      const shared = diffieHellman({ privateKey: pkcs8(fromHex(b.ephemeralSeedHex)), publicKey: spki(fromHex(b.recipientPubHex)) });
      expect(shared.toString("hex")).toBe(b.sharedHex);
      const shared2 = diffieHellman({ privateKey: pkcs8(fromHex(b.recipientSeedHex)), publicKey: spki(fromHex(b.ephemeralPubHex)) });
      expect(shared2.toString("hex")).toBe(b.sharedHex);
      const key = Buffer.from(
        hkdfSync("sha256", shared, concatBytes(fromHex(b.ephemeralPubHex), fromHex(b.recipientPubHex)), `seal/${b.context}`, 32),
      );
      expect(key.toString("hex")).toBe(b.boxKeyHex);
      const box = fromHex(b.boxHex);
      expect(toHex(box.subarray(0, 5))).toBe("464c533101");
      expect(toHex(box.subarray(5, 37))).toBe(b.ephemeralPubHex);
      const d = createDecipheriv("aes-256-gcm", key, box.subarray(37, 49));
      d.setAAD(concatBytes(box.subarray(0, 49), utf8(b.context)));
      d.setAuthTag(box.subarray(box.length - 16));
      const plain = Buffer.concat([d.update(box.subarray(49, box.length - 16)), d.final()]);
      expect(plain.toString("hex")).toBe(b.plaintextHex);
    }
  });

  it("FST1 statements are Ed25519 over the prefix and the canonical body", () => {
    for (const s of v.statements) {
      const pub = createPublicKey({
        key: Buffer.concat([Buffer.from("302a300506032b6570032100", "hex"), fromHex(s.signerPubHex)]),
        format: "der",
        type: "spki",
      });
      const msg = Buffer.from(`folevi/e2ee/v1/statement\n${s.kind}\n${s.body}`, "utf8");
      expect(nodeVerify(null, msg, pub, fromBase64Url(s.sig))).toBe(true);
    }
  });

  it("MACs, commit and codes", () => {
    for (const m of v.macs) {
      const mac = createHmac("sha256", fromHex(m.keyHex))
        .update(concatBytes(utf8(m.context), new Uint8Array([0]), fromHex(m.plaintextHex)))
        .digest()
        .subarray(0, 16);
      expect(Buffer.from(mac).toString("base64url")).toBe(m.mac);
    }
    const a = v.approval;
    const commit = createHash("sha256")
      .update("folevi/e2ee/v1/approval-commit")
      .update(fromHex(a.newNonceHex))
      .update(fromHex(a.newXHex))
      .update(fromHex(a.newEdHex))
      .digest("hex");
    expect(commit).toBe(a.commitHex);
    const h = createHash("sha256")
      .update("folevi/e2ee/v1/approval-code")
      .update(Buffer.concat([a.newXHex, a.newEdHex, a.approverEdHex, a.accountXHex, a.accountEdHex, a.approverNonceHex, a.newNonceHex].map((x) => fromHex(x))))
      .digest();
    expect(String(((h[0]! << 12) | (h[1]! << 4) | (h[2]! >> 4)) % 1_000_000).padStart(6, "0")).toBe(a.code);
    for (const m of v.memberCodes) {
      const d = createHash("sha256").update("folevi/e2ee/v1/member-code").update(fromHex(m.ed25519PubHex)).digest();
      const n = Number(BigInt("0x" + d.subarray(0, 5).toString("hex")) % 1_000_000_000_000n);
      expect(String(n).padStart(12, "0")).toBe(m.code);
    }
  });

  it("Argon2id outputs match node:crypto's argon2 (Node 24+)", async () => {
    const nodeCrypto = (await import("node:crypto")) as unknown as {
      argon2Sync?: (alg: string, o: Record<string, unknown>) => Buffer;
    };
    if (!nodeCrypto.argon2Sync) return;
    for (const a of v.argon2id) {
      const out = nodeCrypto.argon2Sync("argon2id", {
        message: Buffer.from(a.passphrase.normalize("NFC"), "utf8"),
        nonce: fromHex(a.saltHex),
        parallelism: a.p,
        tagLength: a.dkLen,
        memory: a.m,
        passes: a.t,
      });
      expect(out.toString("hex"), a.passphrase).toBe(a.outputHex);
    }
  });

  it("recovery key text encodes 160 key bits and a 20-bit SHA-256 check", () => {
    const alphabet = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
    for (const k of v.recoveryKeys) {
      const check = createHash("sha256").update("folevi/e2ee/v1/recovery-key").update(fromHex(k.bytesHex)).digest();
      const bits = BigInt("0x" + k.bytesHex) * (1n << 20n) + (BigInt("0x" + check.subarray(0, 3).toString("hex")) >> 4n);
      let text = "";
      for (let i = 35; i >= 0; i--) text += alphabet[Number((bits >> BigInt(i * 5)) & 31n)];
      expect(k.text).toBe(text.match(/.{4}/g)!.join("-"));
    }
    expect(v.recoveryParse.filter((p) => p.bytesHex === null).length).toBe(4);
  });
});
