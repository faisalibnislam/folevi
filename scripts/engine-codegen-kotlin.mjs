#!/usr/bin/env node
// Generates the Kotlin side of the native bridge contract (docs/NATIVE_APP_PLAN.md section 3.3,
// docs/ANDROID_NATIVE_PLAN.md) from apps/web/src/lib/engine/protocol.ts, the single source of truth, into
// apps/android/engine/src/main/java/com/folevi/engine/generated/. It is the Android twin of
// scripts/engine-codegen.mjs (which writes the Swift for iPhone, iPad and Mac) and maps the same way:
//
//   EngineModels.kt  every exported interface as a @Serializable data class (doc comments carried over), string
//                    literal unions as enum classes, `T | null` as a nullable that is always sent, `?` as a
//                    nullable left out when null, `x?: T | null` as Patch<T> (left out, null or a value),
//                    `Record<string, T>` as Map<String, T>, `unknown` as JsonElement
//   EngineApi.kt     the constants, the schema hash, the name enums, one typed spec factory per view, list view,
//                    command and editor command (`Views.home()`, `Commands.noteStar(ids, true)`), the
//                    EngineEvent sealed interface with each event's data, and a catalog of serializers by name
//
//   node scripts/engine-codegen-kotlin.mjs           write the files (also `pnpm engine:gen:kotlin`)
//   node scripts/engine-codegen-kotlin.mjs --check   fail when they're stale (CI)
//
// Numbers become Long (Swift's Int is 64-bit too), except the same overrides as the Swift codegen (timestamps,
// CSS lengths, the editor's text size, coordinates), which become Double. Enum entries are UPPER_SNAKE so no
// contract value can clash with a Kotlin keyword or with Enum's own `name` and `ordinal`.
//
// Encoding rules the client's Json must use (FoleviJson in the engine module): ignoreUnknownKeys = true (a newer
// engine may add fields), encodeDefaults = false (so `?` fields and Patch.Keep stay out), explicitNulls = true
// (so a required `T | null` is sent as null), coerceInputValues = true.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(repo, "apps/web/src/lib/engine/protocol.ts");
const OUT_DIR = resolve(repo, "apps/android/engine/src/main/java/com/folevi/engine/generated");
const PKG = "com.folevi.engine.generated";
const check = process.argv.includes("--check");
const HEADER = `// Generated by scripts/engine-codegen-kotlin.mjs from apps/web/src/lib/engine/protocol.ts. Do not edit.\n// Regenerate with \`pnpm engine:gen:kotlin\`; CI fails when this file is stale.`;

// The envelope is hand-written in Kotlin (com.folevi.engine.protocol.Envelope): its payloads are typed per
// subscription. These types are skipped here, as in the Swift codegen.
const SKIP = new Set([
  "ToEngine",
  "FromEngine",
  "Reply",
  "ReplyOk",
  "ReplyError",
  "UpdateMessage",
  "EventMessage",
  "EngineBatch",
  "HelloMessage",
  "WatchMessage",
  "UnwatchMessage",
  "WindowMessage",
  "QueryMessage",
  "CommandMessage",
  "EditorMessage",
  "ViewMap",
  "ListViewMap",
  "CommandMap",
  "EditorCommandMap",
  "EventMap",
]);
const MAPS = { views: "ViewMap", lists: "ListViewMap", commands: "CommandMap", editor: "EditorCommandMap", events: "EventMap" };
/** Property names whose numbers are Double rather than Long (the Swift codegen's NUMBER_OVERRIDES). */
const NUMBER_OVERRIDES = [/^spacing$/, /^pull$/, /At$/, /^at$/, /^top$/, /^bottom$/, /^editorZooms?$/, /^[xy]$/, /^sizes$/, /^px[A-Z]/];
const KOTLIN_KEYWORDS = new Set(
  "as break class continue do else false for fun if in interface is null object package return super this throw true try typealias typeof val var when while".split(" "),
);
/** Names a model must not take: they would shadow what the generated code uses. */
const RESERVED_TYPES = new Set(["String", "Boolean", "Long", "Double", "Int", "List", "Map", "Unit", "Any", "Nothing", "Patch", "JsonElement", "Serializable", "SerialName"]);

const warnings = [];
const text = readFileSync(SOURCE, "utf8");
const sf = ts.createSourceFile(SOURCE, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);

// ---------------------------------------------------------------------------------------------------------------
// Collect declarations (as the Swift codegen does)
// ---------------------------------------------------------------------------------------------------------------

const interfaces = new Map();
const aliases = new Map();
const consts = new Map();
const order = [];
for (const st of sf.statements) {
  if (ts.isInterfaceDeclaration(st)) {
    interfaces.set(st.name.text, st);
    order.push(st.name.text);
  } else if (ts.isTypeAliasDeclaration(st)) {
    aliases.set(st.name.text, st);
    order.push(st.name.text);
  } else if (ts.isVariableStatement(st)) {
    for (const d of st.declarationList.declarations) if (ts.isIdentifier(d.name) && d.initializer) consts.set(d.name.text, d.initializer);
  }
}
for (const n of order) if (RESERVED_TYPES.has(n)) throw new Error(`protocol.ts: a type named ${n} would shadow Kotlin's own; rename it`);

const unwrap = (n) => {
  while (n && (ts.isParenthesizedTypeNode(n) || ts.isAsExpression(n) || ts.isSatisfiesExpression?.(n))) n = n.type && ts.isParenthesizedTypeNode(n) ? n.type : n.expression ?? n.type;
  return n;
};

function docOf(node) {
  const lines = [];
  for (const d of node.jsDoc ?? []) {
    const c = typeof d.comment === "string" ? d.comment : (d.comment ?? []).map((p) => p.text ?? "").join("");
    if (c) lines.push(...c.split("\n"));
  }
  return lines.map((l) => l.trimEnd());
}

const pascal = (s) =>
  s
    .replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
    .replace(/^./, (c) => c.toUpperCase());
const camel = (s) => {
  const p = pascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
};
const ident = (s) => (KOTLIN_KEYWORDS.has(s) ? `\`${s}\`` : s);
const fnName = (raw) => {
  let n = camel(raw);
  if (!n) n = "empty";
  if (/^[0-9]/.test(n)) n = `v${n}`;
  return ident(n);
};
/** `places.list` -> PLACES_LIST, `noteStyle` -> NOTE_STYLE. */
const entryName = (raw) => {
  let n = raw
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase();
  if (!n) n = "EMPTY";
  if (/^[0-9]/.test(n)) n = `V_${n}`;
  return n;
};
const stringLiteralsOf = (union) => {
  const out = [];
  for (const t of union.types) {
    const u = unwrap(t);
    if (ts.isLiteralTypeNode(u) && ts.isStringLiteral(u.literal)) out.push(u.literal.text);
    else return null;
  }
  return out;
};
const isNullish = (t) => {
  const u = unwrap(t);
  return (ts.isLiteralTypeNode(u) && u.literal.kind === ts.SyntaxKind.NullKeyword) || u.kind === ts.SyntaxKind.UndefinedKeyword;
};

function enumAlias(name) {
  const a = aliases.get(name);
  if (!a || a.typeParameters) return null;
  const t = unwrap(a.type);
  if (ts.isUnionTypeNode(t)) return stringLiteralsOf(t);
  if (ts.isLiteralTypeNode(t) && ts.isStringLiteral(t.literal)) return [t.literal.text];
  return null;
}
const isKeyofAlias = (name) => {
  const a = aliases.get(name);
  return Boolean(a && ts.isTypeOperatorNode(unwrap(a.type)) && unwrap(a.type).operator === ts.SyntaxKind.KeyOfKeyword);
};
const singular = (p) => (p ? p.replace(/ies$/, "y").replace(/s$/, "") : p);

// ---------------------------------------------------------------------------------------------------------------
// Type mapping
// ---------------------------------------------------------------------------------------------------------------

/**
 * Maps a TS type node to Kotlin. `ctx.nested` collects nested declarations (inline enums and classes) for the
 * owner, `ctx.path` is the owner's qualified Kotlin name. Returns { type, optional, nestedName }.
 */
function mapType(node, ctx) {
  const n = unwrap(node);
  switch (n.kind) {
    case ts.SyntaxKind.StringKeyword:
      return { type: "String" };
    case ts.SyntaxKind.BooleanKeyword:
      return { type: "Boolean" };
    case ts.SyntaxKind.NumberKeyword:
      return { type: ctx.double || NUMBER_OVERRIDES.some((r) => r.test(ctx.prop ?? "")) ? "Double" : "Long" };
    case ts.SyntaxKind.UnknownKeyword:
    case ts.SyntaxKind.AnyKeyword:
    case ts.SyntaxKind.NeverKeyword:
      return { type: "JsonElement" };
  }
  if (ts.isLiteralTypeNode(n)) {
    if (ts.isStringLiteral(n.literal)) return { type: "String" };
    if (n.literal.kind === ts.SyntaxKind.TrueKeyword || n.literal.kind === ts.SyntaxKind.FalseKeyword) return { type: "Boolean" };
    if (ts.isNumericLiteral(n.literal)) return { type: "Long" };
  }
  if (ts.isArrayTypeNode(n)) {
    const inner = mapType(n.elementType, { ...ctx, prop: singular(ctx.prop), double: NUMBER_OVERRIDES.some((r) => r.test(ctx.prop ?? "")) });
    return { type: `List<${inner.type}${inner.optional ? "?" : ""}>`, nestedName: inner.nestedName };
  }
  if (ts.isTypeOperatorNode(n) && n.operator === ts.SyntaxKind.ReadonlyKeyword) return mapType(n.type, ctx);
  if (ts.isUnionTypeNode(n)) {
    const rest = n.types.filter((t) => !isNullish(t));
    const optional = rest.length !== n.types.length;
    if (rest.length === 1) {
      const m = mapType(rest[0], ctx);
      return { type: m.type, optional: optional || m.optional, nestedName: m.nestedName };
    }
    const lits = stringLiteralsOf({ types: rest });
    if (lits) {
      const enumName = pascal(ctx.prop ?? "Value");
      ctx.nested.push(emitEnum(enumName, lits, [], "    "));
      return { type: `${ctx.path}.${enumName}`, optional, nestedName: enumName };
    }
    if (rest.every((t) => ts.isTypeReferenceNode(unwrap(t)) && (enumAlias(unwrap(t).typeName.getText(sf)) || isKeyofAlias(unwrap(t).typeName.getText(sf))))) {
      return { type: "String", optional };
    }
    warnings.push(`${ctx.owner}.${ctx.prop}: union ${n.getText(sf)} mapped to JsonElement`);
    return { type: "JsonElement", optional };
  }
  if (ts.isTypeReferenceNode(n)) {
    const name = n.typeName.getText(sf);
    if (name === "Record" && n.typeArguments?.length === 2) {
      const value = unwrap(n.typeArguments[1]);
      if (value.kind === ts.SyntaxKind.NeverKeyword) return { type: "EmptyArgs" };
      const inner = mapType(value, { ...ctx, prop: singular(ctx.prop) });
      return { type: `Map<String, ${inner.type}${inner.optional ? "?" : ""}>` };
    }
    if (name === "Array" && n.typeArguments?.length === 1) return { type: `List<${mapType(n.typeArguments[0], ctx).type}>` };
    if (isKeyofAlias(name)) return { type: name };
    if (interfaces.has(name) || aliases.has(name)) return { type: name };
    warnings.push(`${ctx.owner}.${ctx.prop}: unknown type ${name} mapped to JsonElement`);
    return { type: "JsonElement" };
  }
  if (ts.isTypeLiteralNode(n)) {
    const className = pascal(ctx.prop ?? "Value");
    ctx.nested.push(emitClass(className, n.members, [], "    ", `${ctx.path}.${className}`));
    return { type: `${ctx.path}.${className}`, nestedName: className };
  }
  warnings.push(`${ctx.owner}.${ctx.prop}: ${n.getText(sf)} mapped to JsonElement`);
  return { type: "JsonElement" };
}

// ---------------------------------------------------------------------------------------------------------------
// Emitters
// ---------------------------------------------------------------------------------------------------------------

// KDoc text can't hold a comment opener or closer (Kotlin nests block comments), so both get a space.
const kdocSafe = (l) => l.replace(/\/\*/g, "/ *").replace(/\*\//g, "* /");
function docBlock(lines, indent) {
  if (!lines.length) return "";
  if (lines.length === 1) return `${indent}/** ${kdocSafe(lines[0])} */`;
  return [`${indent}/**`, ...lines.map((l) => `${indent} *${l ? " " + kdocSafe(l) : ""}`), `${indent} */`].join("\n");
}

function emitEnum(name, values, doc, indent = "") {
  const lines = [];
  if (doc.length) lines.push(docBlock(doc, indent));
  lines.push(`${indent}@Serializable`, `${indent}enum class ${name}(val value: String) {`);
  const used = new Set();
  for (const v of values) {
    let e = entryName(v);
    while (used.has(e)) e += "_";
    used.add(e);
    lines.push(`${indent}    @SerialName(${JSON.stringify(v)}) ${e}(${JSON.stringify(v)}),`);
  }
  lines.push(`${indent}    ;`, "", `${indent}    companion object {`, `${indent}        fun of(value: String): ${name}? = entries.firstOrNull { it.value == value }`, `${indent}    }`);
  lines.push(`${indent}}`);
  return lines.join("\n");
}

/** `@default false` in a field's doc comment: a Swift literal, translated for Kotlin. */
function initDefaultOf(node, type) {
  for (const d of node.jsDoc ?? []) {
    for (const t of d.tags ?? []) {
      if (t.tagName.text !== "default") continue;
      const c = (typeof t.comment === "string" ? t.comment : (t.comment ?? []).map((p) => p.text ?? "").join("")).trim();
      if (!c) continue;
      if (c === "nil") return "null";
      if (c === "[]") return type.startsWith("Map<") ? "emptyMap()" : "emptyList()";
      if (c === "[:]") return "emptyMap()";
      if (/^\.[A-Za-z]/.test(c)) return `${type}.${entryName(c.slice(1))}`;
      if (/^-?[0-9.]+$/.test(c)) return type === "Double" && !c.includes(".") ? `${c}.0` : c;
      return c; // true, false, "text"
    }
  }
  return null;
}

function propsOf(members, owner, path) {
  const props = [];
  const nested = [];
  for (const m of members) {
    if (!ts.isPropertySignature(m) || !m.type) continue;
    const key = m.name.getText(sf).replace(/^["']|["']$/g, "");
    const ctx = { owner, prop: key, nested, path };
    const mapped = mapType(m.type, ctx);
    const kt = ident(/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ? key : camel(key));
    const optional = Boolean(m.questionToken) || Boolean(mapped.optional);
    props.push({
      key,
      kt,
      type: mapped.type,
      nestedName: mapped.nestedName,
      optional,
      nullable: !m.questionToken && Boolean(mapped.optional),
      patch: Boolean(m.questionToken) && Boolean(mapped.optional),
      doc: docOf(m),
      init: initDefaultOf(m, mapped.type),
    });
  }
  return { props, nested };
}

function emitClass(name, members, doc, indent = "", path = name) {
  const { props, nested } = propsOf(members, path, path);
  const lines = [];
  if (doc.length) lines.push(docBlock(doc, indent));
  lines.push(`${indent}@Serializable`);
  if (!props.length) {
    lines.push(`${indent}class ${name} {`, `${indent}    override fun equals(other: Any?): Boolean = other is ${name}`, `${indent}    override fun hashCode(): Int = ${JSON.stringify(name)}.hashCode()`);
    for (const nd of nested) lines.push("", nd.replace(/^/gm, indent));
    lines.push(`${indent}}`);
    return lines.join("\n");
  }
  lines.push(`${indent}data class ${name}(`);
  for (const p of props) {
    if (p.doc.length) lines.push(docBlock(p.doc, indent + "    "));
    const serial = p.kt.replace(/`/g, "") === p.key ? "" : `@SerialName(${JSON.stringify(p.key)}) `;
    let decl;
    if (p.patch) decl = `val ${p.kt}: Patch<${p.type}> = Patch.Keep`;
    else if (p.optional && !p.nullable) decl = `val ${p.kt}: ${p.type}? = null`;
    else if (p.nullable) decl = `val ${p.kt}: ${p.type}?${p.init !== null ? ` = ${p.init}` : ""}`;
    else decl = `val ${p.kt}: ${p.type}${p.init !== null ? ` = ${p.init}` : ""}`;
    // A field with a default that is still always sent (`@default`, or `T | null` defaulting to null).
    const always = p.init !== null && !(p.optional && !p.nullable) && !p.patch ? "@EncodeDefault " : "";
    lines.push(`${indent}    ${always}${serial}${decl},`);
  }
  lines.push(`${indent})${nested.length ? " {" : ""}`);
  if (nested.length) {
    for (const nd of nested) lines.push(nd.replace(/^/gm, indent), "");
    lines.pop();
    lines.push(`${indent}}`);
  }
  return lines.join("\n");
}

// ---------------------------------------------------------------------------------------------------------------
// Models
// ---------------------------------------------------------------------------------------------------------------

const models = [];
const modelKinds = new Map(); // name -> "class" | "enum" | "alias:String" | "empty"
for (const name of order) {
  if (SKIP.has(name)) continue;
  if (interfaces.has(name)) {
    const decl = interfaces.get(name);
    if (decl.typeParameters) continue;
    models.push(emitClass(name, decl.members, docOf(decl)));
    modelKinds.set(name, "class");
    continue;
  }
  const a = aliases.get(name);
  if (!a || a.typeParameters) continue;
  if (isKeyofAlias(name)) continue;
  const t = unwrap(a.type);
  const lits = enumAlias(name);
  const doc = docOf(a);
  if (lits) {
    models.push(emitEnum(name, lits, doc));
    modelKinds.set(name, "enum");
  } else if (t.kind === ts.SyntaxKind.StringKeyword) {
    models.push(`${doc.length ? docBlock(doc, "") + "\n" : ""}typealias ${name} = String`);
    modelKinds.set(name, "alias:String");
  } else if (ts.isTypeReferenceNode(t) && t.typeName.getText(sf) === "Record" && unwrap(t.typeArguments?.[1])?.kind === ts.SyntaxKind.NeverKeyword) {
    models.push(`${doc.length ? docBlock(doc, "") + "\n" : ""}@Serializable\nobject ${name}`);
    modelKinds.set(name, "empty");
  } else if (ts.isTypeLiteralNode(t)) {
    models.push(emitClass(name, t.members, doc));
    modelKinds.set(name, "class");
  } else {
    warnings.push(`type ${name} = ${t.getText(sf)} skipped`);
  }
}

// ---------------------------------------------------------------------------------------------------------------
// The maps, names and constants
// ---------------------------------------------------------------------------------------------------------------

function mapEntries(mapName) {
  const decl = interfaces.get(mapName);
  if (!decl) throw new Error(`protocol.ts has no ${mapName}`);
  return decl.members.filter(ts.isPropertySignature).map((m) => {
    const key = m.name.getText(sf).replace(/^["']|["']$/g, "");
    const fields = {};
    const t = unwrap(m.type);
    if (ts.isTypeLiteralNode(t)) {
      for (const f of t.members.filter(ts.isPropertySignature)) fields[f.name.getText(sf)] = unwrap(f.type).getText(sf);
    } else {
      fields.data = t.getText(sf);
    }
    return { key, fields, doc: docOf(m) };
  });
}

function constArray(name) {
  let n = consts.get(name);
  while (n && (ts.isAsExpression(n) || ts.isParenthesizedExpression(n) || (ts.isSatisfiesExpression && ts.isSatisfiesExpression(n)))) n = n.expression;
  if (!n || !ts.isArrayLiteralExpression(n)) throw new Error(`protocol.ts: ${name} must be an array literal`);
  return n.elements.map((e) => e.text);
}

function constValue(name) {
  let n = consts.get(name);
  while (n && (ts.isAsExpression(n) || ts.isParenthesizedExpression(n))) n = n.expression;
  if (!n) throw new Error(`protocol.ts has no ${name}`);
  if (ts.isNumericLiteral(n)) return Number(n.text);
  if (ts.isStringLiteral(n)) return n.text;
  if (ts.isBinaryExpression(n)) return Function(`return (${n.getText(sf)})`)();
  throw new Error(`protocol.ts: can't read ${name}`);
}

function fnv1a(s) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16).padStart(8, "0");
}

const names = {
  views: constArray("viewNames"),
  lists: constArray("listViewNames"),
  commands: constArray("commandNames"),
  editor: constArray("editorCommandNames"),
  events: constArray("eventNames"),
};
const entries = Object.fromEntries(Object.entries(MAPS).map(([k, m]) => [k, mapEntries(m)]));
for (const k of Object.keys(MAPS)) {
  const a = [...names[k]].sort().join(",");
  const b = entries[k].map((e) => e.key).sort().join(",");
  if (a !== b) throw new Error(`protocol.ts: the ${k} names list and ${MAPS[k]} differ`);
}
const PROTOCOL_VERSION = constValue("PROTOCOL_VERSION");
const CONTRACT_REVISION = constValue("CONTRACT_REVISION");
// The same hash as the Swift codegen and the engine's hello: equal when this file is current.
const schemaHash = fnv1a([`${PROTOCOL_VERSION}.${CONTRACT_REVISION}`, names.views.join(","), names.lists.join(","), names.commands.join(","), names.editor.join(","), names.events.join(",")].join("|"));
const features = (() => {
  let n = consts.get("FEATURES");
  while (n && (ts.isAsExpression(n) || ts.isParenthesizedExpression(n))) n = n.expression;
  return n && ts.isArrayLiteralExpression(n) ? n.elements.map((e) => e.text) : [];
})();

/** The Kotlin serializer expression for a type named in a map (`HomeValue`, `EmptyArgs`, `string[]`...). */
function serializerOf(typeText) {
  const t = typeText.trim();
  if (t.endsWith("[]")) return `ListSerializer(${serializerOf(t.slice(0, -2))})`;
  if (t === "string" || modelKinds.get(t) === "alias:String") return "String.serializer()";
  if (t === "boolean") return "Boolean.serializer()";
  if (t === "number") return "Long.serializer()";
  if (t === "null" || t === "unknown") return "JsonElement.serializer()";
  if (modelKinds.has(t)) return `${t}.serializer()`;
  throw new Error(`engine-codegen-kotlin: no serializer for ${t}`);
}
const kotlinTypeOf = (typeText) => {
  const t = typeText.trim();
  if (t.endsWith("[]")) return `List<${kotlinTypeOf(t.slice(0, -2))}>`;
  return { string: "String", boolean: "Boolean", number: "Long", null: "JsonElement", unknown: "JsonElement" }[t] ?? t;
};

function argFields(typeName) {
  if (typeName === "EmptyArgs") return [];
  const decl = interfaces.get(typeName);
  if (!decl || decl.typeParameters) return null;
  return propsOf(decl.members, typeName, typeName).props;
}

function nameEnum(enumName, list, doc) {
  return emitEnum(enumName, list, doc);
}

function specs({ container, specClass, list, valueField, doc }) {
  const out = [docBlock([doc], ""), `object ${container} {`];
  for (const e of list) {
    const argsType = e.fields.args;
    const valueType = e.fields[valueField];
    const fn = fnName(e.key);
    const head = `${specClass}<${kotlinTypeOf(argsType)}, ${kotlinTypeOf(valueType)}>`;
    const make = (argsExpr) => `${specClass}(${JSON.stringify(e.key)}, ${argsExpr}, ${serializerOf(argsType)}, ${serializerOf(valueType)})`;
    if (e.doc.length) out.push(docBlock(e.doc, "    "));
    const fields = argFields(argsType);
    if (argsType === "EmptyArgs" || (fields && fields.length === 0 && modelKinds.get(argsType) === "empty")) {
      out.push(`    fun ${fn}(): ${head} = ${make("EmptyArgs")}`);
    } else if (fields && fields.length > 0) {
      const params = fields
        .map((p) => {
          const name = p.kt;
          if (p.patch) return `${name}: Patch<${p.type}> = Patch.Keep`;
          if (p.optional) return `${name}: ${p.type}? = null`;
          return `${name}: ${p.type}${p.init !== null ? ` = ${p.init}` : ""}`;
        })
        .join(", ");
      const call = fields.map((p) => `${p.kt} = ${p.kt}`).join(", ");
      out.push(`    fun ${fn}(${params}): ${head} = ${make(`${argsType}(${call})`)}`);
    } else {
      out.push(`    fun ${fn}(args: ${kotlinTypeOf(argsType)}): ${head} = ${make("args")}`);
    }
  }
  out.push("}");
  return out.join("\n");
}

const eventCases = entries.events.map((e) => ({ key: e.key, name: pascal(e.key), type: e.fields.data, doc: e.doc }));
