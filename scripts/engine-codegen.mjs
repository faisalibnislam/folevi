#!/usr/bin/env node
// Generates the Swift side of the native bridge contract (docs/NATIVE_APP_PLAN.md section 3.3) from
// apps/web/src/lib/engine/protocol.ts, the single source of truth, into
// apps/native-kit/Sources/FoleviEngine/Generated/:
//
//   EngineModels.swift  every exported interface as a Codable struct (doc comments carried over), string literal
//                       unions as String enums, `T | null` and `?` as optionals, `Record<string, T>` as
//                       dictionaries, `unknown` as JSONValue
//   EngineAPI.swift     the constants, the schema hash, the name enums (ViewName, ListViewName, CommandName,
//                       EditorCommandName, EventName), one typed spec per view, list view, command and editor
//                       command (so `client.watch(.home())`, `client.command(.noteStar(ids: ids, starred: true))`
//                       are typed end to end), and `EngineEvent` with each event's data
//
//   node scripts/engine-codegen.mjs           write the files (also `pnpm engine:gen`)
//   node scripts/engine-codegen.mjs --check   fail when they're stale (CI)
//
// It reads the TypeScript syntax tree directly (the compiler API, no checker), so protocol.ts must keep to the
// codegen-friendly rules written at its top. Anything it can't map becomes JSONValue with a warning, never a
// silent guess. Numbers become Int, except timestamps (`...At`, `at`) and CSS lengths (`top`, `bottom`) and the editor's text size (`editorZoom`), which
// become Double (NUMBER_OVERRIDES below).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(repo, "apps/web/src/lib/engine/protocol.ts");
const OUT_DIR = resolve(repo, "apps/native-kit/Sources/FoleviEngine/Generated");
const check = process.argv.includes("--check");
const HEADER = `// Generated by scripts/engine-codegen.mjs from apps/web/src/lib/engine/protocol.ts. Do not edit.\n// Regenerate with \`pnpm engine:gen\`; CI fails when this file is stale.`;

// The envelope is hand-written in Swift (FoleviEngine/Protocol/Envelope.swift): its payloads are typed per
// subscription and decoded in one pass. These types are skipped here.
const SKIP = new Set([
  "ToEngine",
  "FromEngine",
  "Reply",
  "ReplyOk",
  "ReplyError",
  "UpdateMessage",
  "EventMessage",
  "EngineBatch",
  "HelloMessage",
  "WatchMessage",
  "UnwatchMessage",
  "WindowMessage",
  "QueryMessage",
  "CommandMessage",
  "EditorMessage",
  "ViewMap",
  "ListViewMap",
  "CommandMap",
  "EditorCommandMap",
  "EventMap",
]);
const MAPS = { views: "ViewMap", lists: "ListViewMap", commands: "CommandMap", editor: "EditorCommandMap", events: "EventMap" };
/** Property names whose numbers are Double rather than Int. */
const NUMBER_OVERRIDES = [/At$/, /^at$/, /^top$/, /^bottom$/, /^editorZooms?$/];
const SWIFT_KEYWORDS = new Set(
  "associatedtype class deinit enum extension fileprivate func import init inout internal let open operator private precedencegroup protocol public rethrows static struct subscript typealias var break case catch continue default defer do else fallthrough for guard if in repeat return throw switch where while as false is nil self Self super throws true try Any Type".split(" "),
);

const warnings = [];
const text = readFileSync(SOURCE, "utf8");
const sf = ts.createSourceFile(SOURCE, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);

// ---------------------------------------------------------------------------------------------------------------
// Collect declarations
// ---------------------------------------------------------------------------------------------------------------

const interfaces = new Map(); // name -> InterfaceDeclaration
const aliases = new Map(); // name -> TypeAliasDeclaration
const consts = new Map(); // name -> initializer
const order = []; // declaration order of emitted names
for (const st of sf.statements) {
  if (ts.isInterfaceDeclaration(st)) {
    interfaces.set(st.name.text, st);
    order.push(st.name.text);
  } else if (ts.isTypeAliasDeclaration(st)) {
    aliases.set(st.name.text, st);
    order.push(st.name.text);
  } else if (ts.isVariableStatement(st)) {
    for (const d of st.declarationList.declarations) if (ts.isIdentifier(d.name) && d.initializer) consts.set(d.name.text, d.initializer);
  }
}

const unwrap = (n) => {
  while (n && (ts.isParenthesizedTypeNode(n) || ts.isAsExpression(n) || ts.isSatisfiesExpression?.(n))) n = n.type && ts.isParenthesizedTypeNode(n) ? n.type : n.expression ?? n.type;
  return n;
};

function docOf(node) {
  const docs = node.jsDoc ?? [];
  const lines = [];
  for (const d of docs) {
    const c = typeof d.comment === "string" ? d.comment : (d.comment ?? []).map((p) => p.text ?? "").join("");
    if (c) lines.push(...c.split("\n"));
  }
  // Trailing line comments on a union member are kept too (`| "a" // what a is`).
  return lines.map((l) => l.trimEnd());
}

const pascal = (s) =>
  s
    .replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
    .replace(/^./, (c) => c.toUpperCase());
const camel = (s) => {
  const p = pascal(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
};
const ident = (s) => (SWIFT_KEYWORDS.has(s) ? `\`${s}\`` : s);
const caseName = (raw) => {
  let n = camel(raw);
  if (!n) n = "empty";
  if (/^[0-9]/.test(n)) n = `v${n}`;
  return ident(n);
};
const stringLiteralsOf = (union) => {
  const out = [];
  for (const t of union.types) {
    const u = unwrap(t);
    if (ts.isLiteralTypeNode(u) && ts.isStringLiteral(u.literal)) out.push(u.literal.text);
    else return null;
  }
  return out;
};
const isNullish = (t) => {
  const u = unwrap(t);
  return (ts.isLiteralTypeNode(u) && u.literal.kind === ts.SyntaxKind.NullKeyword) || u.kind === ts.SyntaxKind.UndefinedKeyword;
};

/** A type alias that is a union of string literals (an enum), or null. */
function enumAlias(name) {
  const a = aliases.get(name);
  if (!a || a.typeParameters) return null;
  const t = unwrap(a.type);
  if (ts.isUnionTypeNode(t)) return stringLiteralsOf(t);
  if (ts.isLiteralTypeNode(t) && ts.isStringLiteral(t.literal)) return [t.literal.text];
  return null;
}

