function mapEntries(mapName) {
  const decl = interfaces.get(mapName);
  if (!decl) throw new Error(`protocol.ts has no ${mapName}`);
  return decl.members.filter(ts.isPropertySignature).map((m) => {
    const key = m.name.getText(sf).replace(/^["']|["']$/g, "");
    const fields = {};
    const t = unwrap(m.type);
    if (ts.isTypeLiteralNode(t)) {
      for (const f of t.members.filter(ts.isPropertySignature)) fields[f.name.getText(sf)] = unwrap(f.type).getText(sf);
    } else {
      fields.data = t.getText(sf);
    }
    return { key, fields, doc: docOf(m) };
  });
}

function constArray(name) {
  const init = consts.get(name);
  let n = init;
  while (n && (ts.isAsExpression(n) || ts.isParenthesizedExpression(n) || (ts.isSatisfiesExpression && ts.isSatisfiesExpression(n)))) n = n.expression;
  if (!n || !ts.isArrayLiteralExpression(n)) throw new Error(`protocol.ts: ${name} must be an array literal`);
  return n.elements.map((e) => e.text);
}

function constValue(name) {
  let n = consts.get(name);
  while (n && (ts.isAsExpression(n) || ts.isParenthesizedExpression(n))) n = n.expression;
  if (!n) throw new Error(`protocol.ts has no ${name}`);
  if (ts.isNumericLiteral(n)) return Number(n.text);
  if (ts.isStringLiteral(n)) return n.text;
  if (ts.isBinaryExpression(n)) return Function(`return (${n.getText(sf)})`)();
  throw new Error(`protocol.ts: can't read ${name}`);
}

function fnv1a(s) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16).padStart(8, "0");
}

const names = {
  views: constArray("viewNames"),
  lists: constArray("listViewNames"),
  commands: constArray("commandNames"),
  editor: constArray("editorCommandNames"),
  events: constArray("eventNames"),
};
const entries = Object.fromEntries(Object.entries(MAPS).map(([k, m]) => [k, mapEntries(m)]));
for (const k of Object.keys(MAPS)) {
  const a = [...names[k]].sort().join(",");
  const b = entries[k].map((e) => e.key).sort().join(",");
  if (a !== b) throw new Error(`protocol.ts: the ${k} names list and ${MAPS[k]} differ`);
}
const PROTOCOL_VERSION = constValue("PROTOCOL_VERSION");
const CONTRACT_REVISION = constValue("CONTRACT_REVISION");
const schemaHash = fnv1a([`${PROTOCOL_VERSION}.${CONTRACT_REVISION}`, names.views.join(","), names.lists.join(","), names.commands.join(","), names.editor.join(","), names.events.join(",")].join("|"));
const features = (() => {
  let n = consts.get("FEATURES");
  while (n && (ts.isAsExpression(n) || ts.isParenthesizedExpression(n))) n = n.expression;
  return n && ts.isArrayLiteralExpression(n) ? n.elements.map((e) => e.text) : [];
})();

/** The fields of an args interface, for flattened request functions; null when it isn't a plain interface. */
function argFields(typeName) {
  if (typeName === "EmptyArgs") return [];
  const decl = interfaces.get(typeName);
  if (!decl || decl.typeParameters) return null;
  return propsOf(decl.members, typeName).props;
}

function nameEnum(enumName, list, doc) {
  return emitEnum(enumName, list, doc);
}

function specs({ kind, protocol, container, list, assoc, factoryDoc }) {
  const out = [`/// ${factoryDoc}`, `public enum ${container} {`];
  const factories = [];
  for (const e of list) {
    const typeName = pascal(e.key);
    const argsType = e.fields.args;
    // Module-qualified: a spec may share its model's name (Views.NoteMeta's Value is FoleviEngine.NoteMeta).
    const q = (t) => `FoleviEngine.${t}`;
    const assocLines = assoc.map(([alias, field]) => `        public typealias ${alias} = ${q(e.fields[field])}`);
    out.push(
      ...(e.doc.length ? [docLines(e.doc, "    ")] : []),
      `    public struct ${typeName}: ${protocol} {`,
      `        public static let name = ${JSON.stringify(e.key)}`,
      `        public typealias Args = ${q(argsType)}`,
      ...assocLines,
      `        public var args: Args`,
      `        public init(_ args: Args${argsType === "EmptyArgs" ? " = .init()" : ""}) { self.args = args }`,
      `    }`,
    );
    const fn = caseName(e.key);
    const fields = argFields(argsType);
    if (fields && fields.length === 0) {
      factories.push(`public extension ${protocol} where Self == ${container}.${typeName} {\n    static var ${fn}: Self { Self() }\n}`);
    } else if (fields) {
      // Types nested in the args struct (inline enums) are qualified with it.
      const typeOf = (p) => (p.nestedName ? p.type.replace(p.nestedName, `${q(argsType)}.${p.nestedName}`) : p.type);
      const params = fields.map((p) => `${p.swift.replace(/`/g, "")}: ${typeOf(p)}${p.optional ? "? = nil" : ""}`).join(", ");
      const call = fields.map((p) => `${p.swift.replace(/`/g, "")}: ${p.swift}`).join(", ");
      factories.push(`public extension ${protocol} where Self == ${container}.${typeName} {\n    static func ${fn}(${params}) -> Self { Self(${q(argsType)}(${call})) }\n}`);
    } else {
      factories.push(`public extension ${protocol} where Self == ${container}.${typeName} {\n    static func ${fn}(_ args: ${q(argsType)}) -> Self { Self(args) }\n}`);
    }
  }
  out.push("}");
  return [out.join("\n"), ...factories].join("\n\n");
}

