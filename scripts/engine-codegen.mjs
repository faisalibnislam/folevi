// Type mapping
// ---------------------------------------------------------------------------------------------------------------

/**
 * Maps a TS type node to Swift. `nested` collects nested declarations (inline enums and structs) for the owner.
 * Returns { type, optional }.
 */
function mapType(node, ctx) {
  const n = unwrap(node);
  switch (n.kind) {
    case ts.SyntaxKind.StringKeyword:
      return { type: "String" };
    case ts.SyntaxKind.BooleanKeyword:
      return { type: "Bool" };
    case ts.SyntaxKind.NumberKeyword:
      return { type: NUMBER_OVERRIDES.some((r) => r.test(ctx.prop ?? "")) ? "Double" : "Int" };
    case ts.SyntaxKind.UnknownKeyword:
    case ts.SyntaxKind.AnyKeyword:
      return { type: "JSONValue" };
    case ts.SyntaxKind.NeverKeyword:
      return { type: "JSONValue" };
  }
  if (ts.isLiteralTypeNode(n)) {
    if (ts.isStringLiteral(n.literal)) return { type: "String" };
    if (n.literal.kind === ts.SyntaxKind.TrueKeyword || n.literal.kind === ts.SyntaxKind.FalseKeyword) return { type: "Bool" };
    if (ts.isNumericLiteral(n.literal)) return { type: "Int" };
  }
  if (ts.isArrayTypeNode(n)) {
    const inner = mapType(n.elementType, { ...ctx, prop: singular(ctx.prop) });
    return { type: `[${inner.type}${inner.optional ? "?" : ""}]`, nestedName: inner.nestedName };
  }
  if (ts.isTypeOperatorNode(n) && n.operator === ts.SyntaxKind.ReadonlyKeyword) return mapType(n.type, ctx);
  if (ts.isUnionTypeNode(n)) {
    const rest = n.types.filter((t) => !isNullish(t));
    const optional = rest.length !== n.types.length;
    if (rest.length === 1) {
      const m = mapType(rest[0], ctx);
      return { type: m.type, optional: optional || m.optional, nestedName: m.nestedName };
    }
    const lits = stringLiteralsOf({ types: rest });
    if (lits) {
      const enumName = pascal(ctx.prop ?? "Value");
      ctx.nested.push(emitEnum(enumName, lits, [], "    "));
      return { type: enumName, optional, nestedName: enumName };
    }
    // A union of enum aliases (`ViewName | ListViewName`): an open string.
    if (rest.every((t) => ts.isTypeReferenceNode(unwrap(t)) && (enumAlias(unwrap(t).typeName.getText(sf)) || isKeyofAlias(unwrap(t).typeName.getText(sf))))) {
      return { type: "String", optional };
    }
    warnings.push(`${ctx.owner}.${ctx.prop}: union ${n.getText(sf)} mapped to JSONValue`);
    return { type: "JSONValue", optional };
  }
  if (ts.isTypeReferenceNode(n)) {
    const name = n.typeName.getText(sf);
    if (name === "Record" && n.typeArguments?.length === 2) {
      const value = unwrap(n.typeArguments[1]);
      if (value.kind === ts.SyntaxKind.NeverKeyword) return { type: "EmptyArgs" };
      const inner = mapType(value, { ...ctx, prop: singular(ctx.prop) });
      return { type: `[String: ${inner.type}${inner.optional ? "?" : ""}]` };
    }
    if (name === "Array" && n.typeArguments?.length === 1) return { type: `[${mapType(n.typeArguments[0], ctx).type}]` };
    if (isKeyofAlias(name)) return { type: name };
    if (interfaces.has(name) || aliases.has(name)) {
      const a = aliases.get(name);
      if (a && !enumAlias(name)) {
        // Aliases of plain types (SpaceRef = string) become typealiases; follow them for the shape.
        const t = unwrap(a.type);
        if (t.kind === ts.SyntaxKind.StringKeyword) return { type: name };
        if (ts.isTypeReferenceNode(t) && t.typeName.getText(sf) === "Record") return { type: name };
      }
      return { type: name };
    }
    warnings.push(`${ctx.owner}.${ctx.prop}: unknown type ${name} mapped to JSONValue`);
    return { type: "JSONValue" };
  }
  if (ts.isTypeLiteralNode(n)) {
    const structName = pascal(ctx.prop ?? "Value");
    ctx.nested.push(emitStruct(structName, n.members, [], "    ", ctx.owner + "." + structName));
    return { type: structName, nestedName: structName };
  }
  warnings.push(`${ctx.owner}.${ctx.prop}: ${n.getText(sf)} mapped to JSONValue`);
  return { type: "JSONValue" };
}

const singular = (p) => (p ? p.replace(/ies$/, "y").replace(/s$/, "") : p);
const isKeyofAlias = (name) => {
  const a = aliases.get(name);
  return Boolean(a && ts.isTypeOperatorNode(unwrap(a.type)) && unwrap(a.type).operator === ts.SyntaxKind.KeyOfKeyword);
};

// ---------------------------------------------------------------------------------------------------------------
// Emitters
// ---------------------------------------------------------------------------------------------------------------

const docLines = (lines, indent) => lines.map((l) => `${indent}///${l ? " " + l : ""}`).join("\n");

function emitEnum(name, values, doc, indent = "") {
  const lines = [];
  if (doc.length) lines.push(docLines(doc, indent));
  lines.push(`${indent}public enum ${name}: String, Codable, Hashable, Sendable, CaseIterable {`);
  for (const v of values) {
    const c = caseName(v);
    lines.push(`${indent}    case ${c}${c.replace(/`/g, "") === v ? "" : ` = ${JSON.stringify(v)}`}`);
  }
  lines.push(`${indent}}`);
  return lines.join("\n");
}

/**
 * A field added to a type native already builds (demo engines, tests) can say what its memberwise init takes
 * when the argument is left out: `@default false` in its doc comment (a Swift literal). It is still always sent.
 */
function initDefaultOf(node) {
  for (const d of node.jsDoc ?? []) {
    for (const t of d.tags ?? []) {
      if (t.tagName.text !== "default") continue;
      const c = typeof t.comment === "string" ? t.comment : (t.comment ?? []).map((p) => p.text ?? "").join("");
      if (c.trim()) return c.trim();
    }
  }
  return null;
}

function propsOf(members, owner) {
  const props = [];
  const nested = [];
  for (const m of members) {
    if (!ts.isPropertySignature(m) || !m.type) continue;
    const name = m.name.getText(sf).replace(/^["']|["']$/g, "");
    const ctx = { owner, prop: name, nested };
    const mapped = mapType(m.type, ctx);
    props.push({ name, swift: ident(/^[A-Za-z_][A-Za-z0-9_]*$/.test(name) ? name : camel(name)), key: name, type: mapped.type, nestedName: mapped.nestedName, optional: Boolean(m.questionToken) || Boolean(mapped.optional), nullable: !m.questionToken && Boolean(mapped.optional), patch: Boolean(m.questionToken) && Boolean(mapped.optional), doc: docOf(m), init: initDefaultOf(m) });
  }
  return { props, nested };
}

function emitStruct(name, members, doc, indent = "", owner = name) {
  const { props, nested } = propsOf(members, owner);
  const lines = [];
  if (doc.length) lines.push(docLines(doc, indent));
  lines.push(`${indent}public struct ${name}: Codable, Hashable, Sendable {`);
  for (const nd of nested) lines.push(nd.replace(/^/gm, indent), "");
  for (const p of props) {
    if (p.doc.length) lines.push(docLines(p.doc, indent + "    "));
    lines.push(`${indent}    public var ${p.swift}: ${p.patch ? `Patch<${p.type}>` : `${p.type}${p.optional ? "?" : ""}`}`);
  }
  const patched = props.some((p) => p.patch);
  // (A struct with a three-state field codes itself, so it names its keys itself too.)
  if (patched || props.some((p) => p.swift.replace(/`/g, "") !== p.key)) {
    lines.push("", `${indent}    enum CodingKeys: String, CodingKey {`);
    for (const p of props) lines.push(`${indent}        case ${p.swift}${p.swift.replace(/`/g, "") === p.key ? "" : ` = ${JSON.stringify(p.key)}`}`);
    lines.push(`${indent}    }`);
  }
  // A public memberwise init (Swift only synthesizes an internal one); optionals default to nil.
  const params = props.map((p) => `${p.swift.replace(/`/g, "")}: ${p.type}${p.optional ? "? = nil" : p.init !== null ? ` = ${p.init}` : ""}`);
  lines.push("", `${indent}    public init(${params.join(", ")}) {`);
  for (const p of props) lines.push(`${indent}        self.${p.swift.replace(/`/g, "")} = ${p.patch ? `Patch(${p.swift})` : p.swift}`);
  lines.push(`${indent}    }`);
  // A required `T | null` field is always sent, as null when nil (synthesized Codable would leave it out, and the
  // engine refuses a missing one); only `?` fields are left out when nil.
  if (props.some((p) => p.nullable) || patched) {
    // (The container isn't called `c`: a field may be, as PreviewLine's checked `c` is; `self.` keeps them apart.)
    lines.push("", `${indent}    public func encode(to encoder: any Encoder) throws {`, `${indent}        var container = encoder.container(keyedBy: CodingKeys.self)`);
    for (const p of props) lines.push(`${indent}        try container.${p.patch ? "encodePatch" : p.optional && !p.nullable ? "encodeIfPresent" : "encode"}(self.${p.swift.replace(/`/g, "")}, forKey: .${p.swift})`);
    lines.push(`${indent}    }`);
  }
  // A three-state field reads back as left out (.keep), null (.clear) or a value (.set).
  if (patched) {
    lines.push("", `${indent}    public init(from decoder: any Decoder) throws {`, `${indent}        let container = try decoder.container(keyedBy: CodingKeys.self)`);
    for (const p of props) {
      const name = p.swift.replace(/`/g, "");
      if (p.patch) lines.push(`${indent}        self.${name} = try container.decodePatch(${p.type}.self, forKey: .${p.swift})`);
      else if (p.optional) lines.push(`${indent}        self.${name} = try container.decodeIfPresent(${p.type}.self, forKey: .${p.swift})`);
      else lines.push(`${indent}        self.${name} = try container.decode(${p.type}.self, forKey: .${p.swift})`);
    }
    lines.push(`${indent}    }`);
  }
  lines.push(`${indent}}`);
  return lines.join("\n");
}

// ---------------------------------------------------------------------------------------------------------------
// Models
// ---------------------------------------------------------------------------------------------------------------

const models = [];
for (const name of order) {
  if (SKIP.has(name)) continue;
  if (interfaces.has(name)) {
    const decl = interfaces.get(name);
    if (decl.typeParameters) continue;
    models.push(emitStruct(name, decl.members, docOf(decl)));
    continue;
  }
  const a = aliases.get(name);
  if (!a || a.typeParameters) continue;
  if (isKeyofAlias(name)) continue; // emitted from the maps
  const t = unwrap(a.type);
  const lits = enumAlias(name);
  if (lits) {
    models.push(emitEnum(name, lits, docOf(a)));
  } else if (t.kind === ts.SyntaxKind.StringKeyword) {
    models.push(`${docOf(a).length ? docLines(docOf(a), "") + "\n" : ""}public typealias ${name} = String`);
  } else if (ts.isTypeReferenceNode(t) && t.typeName.getText(sf) === "Record" && unwrap(t.typeArguments?.[1])?.kind === ts.SyntaxKind.NeverKeyword) {
    models.push(`${docOf(a).length ? docLines(docOf(a), "") + "\n" : ""}public struct ${name}: Codable, Hashable, Sendable {\n    public init() {}\n}`);
  } else if (ts.isTypeLiteralNode(t)) {
    models.push(emitStruct(name, t.members, docOf(a)));
  } else {
    warnings.push(`type ${name} = ${t.getText(sf)} skipped`);
  }
}

