#!/usr/bin/env node
// The web app's icons for the native apps (docs/MAC_REBUILD_PLAN.md section 3.1): every lucide-react icon that
// apps/web/src imports, copied as drawing data from the installed lucide-react (the same version the web
// draws) into apps/native-kit/Sources/FoleviDesign/Generated/Icons.swift. FoleviDesign's `WebIconView` strokes
// them the way lucide's SVGs do (24 pt grid, round caps and joins, the stroke width scaling with the size).
//
//   pnpm icons:gen            write the Swift file
//   pnpm icons:gen --check    fail if it is out of date (CI)
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const webSrc = join(repo, "apps/web/src");
const out = join(repo, "apps/native-kit/Sources/FoleviDesign/Generated/Icons.swift");
const check = process.argv.includes("--check");

// lucide-react as the web app resolves it.
const require = createRequire(join(repo, "apps/web/package.json"));
const lucideRoot = dirname(dirname(require.resolve("lucide-react")));
const lucideEsm = existsSync(join(lucideRoot, "esm")) ? join(lucideRoot, "esm") : join(lucideRoot, "dist/esm");
const version = JSON.parse(readFileSync(join(dirname(lucideRoot), "package.json"), "utf8")).version;

// Export name (X, XIcon, LucideX) -> icon file name (x).
const exportsToFile = new Map();
for (const m of readFileSync(join(lucideEsm, "lucide-react.mjs"), "utf8").matchAll(/export \{([^}]+)\} from '\.\/icons\/([a-z0-9-]+)\.mjs'/g)) {
  for (const part of m[1].split(",")) {
    const name = part.trim().replace(/^default as /, "");
    if (name) exportsToFile.set(name, m[2]);
  }
}

function walk(dir, acc = []) {
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (/\.(tsx?|jsx?)$/.test(entry)) acc.push(p);
  }
  return acc;
}

const used = new Set();
const unknown = new Set();
for (const file of walk(webSrc)) {
  const text = readFileSync(file, "utf8");
  for (const m of text.matchAll(/import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*["']lucide-react["']/g)) {
    for (const raw of m[1].split(",")) {
      const name = raw.trim().replace(/^type\s+/, "").split(/\s+as\s+/)[0].trim();
      if (!name || /^(LucideIcon|LucideProps|IconNode|createLucideIcon|Icon|icons)$/.test(name)) continue;
      const fileName = exportsToFile.get(name);
      if (fileName) used.add(fileName);
      else unknown.add(name);
    }
  }
}
if (unknown.size) console.warn(`not lucide icons, skipped: ${[...unknown].sort().join(", ")}`);

/** The icon's drawing (`__iconData.node`), from its module (which imports React, as the web app does). */
const nodes = new Map();
for (const fileName of used) {
  const mod = await import(pathToFileURL(join(lucideEsm, "icons", `${fileName}.mjs`)).href);
  if (!Array.isArray(mod.__iconData?.node)) throw new Error(`can't read lucide icon ${fileName}`);
  nodes.set(fileName, mod.__iconData.node);
}
const iconNode = (fileName) => nodes.get(fileName);

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const swiftCase = (s) => {
  const c = camel(s);
  return /^[0-9]/.test(c) ? `i${c}` : ["repeat", "import", "case", "default", "return", "switch", "in", "is", "as", "where", "for", "while", "if", "else", "do", "try", "throw", "let", "var", "func", "self", "super"].includes(c) ? `\`${c}\`` : c;
};
const n = (v) => {
  const x = Number(v);
  if (!Number.isFinite(x)) throw new Error(`not a number: ${v}`);
  return Number.isInteger(x) ? `${x}` : `${x}`;
};
const str = (s) => JSON.stringify(String(s));

function swiftNode([tag, a]) {
  switch (tag) {
    case "path":
      return `.path(${str(a.d)})`;
    case "circle":
      return `.circle(cx: ${n(a.cx)}, cy: ${n(a.cy)}, r: ${n(a.r)})`;
    case "ellipse":
      return `.ellipse(cx: ${n(a.cx)}, cy: ${n(a.cy)}, rx: ${n(a.rx)}, ry: ${n(a.ry)})`;
    case "rect":
      return `.rect(x: ${n(a.x ?? 0)}, y: ${n(a.y ?? 0)}, width: ${n(a.width)}, height: ${n(a.height)}, rx: ${n(a.rx ?? a.ry ?? 0)}, ry: ${n(a.ry ?? a.rx ?? 0)})`;
    case "line":
      return `.line(x1: ${n(a.x1)}, y1: ${n(a.y1)}, x2: ${n(a.x2)}, y2: ${n(a.y2)})`;
    case "polyline":
    case "polygon":
      return `.${tag}(${str(a.points)})`;
    default:
      throw new Error(`unknown lucide element ${tag}`);
  }
}

const names = [...used].sort();
const swift = `// Generated by scripts/icons-codegen.mjs from lucide-react ${version}. Do not edit.
// The icons apps/web/src imports (${names.length}), as lucide draws them on a 24 pt grid.

public enum WebIcon: String, CaseIterable, Sendable {
${names.map((x) => `    case ${swiftCase(x)} = ${str(x)}`).join("\n")}

    /// The icon's elements, in drawing order.
    public var nodes: [WebIconNode] {
        switch self {
${names.map((x) => `        case .${swiftCase(x).replace(/`/g, "")}: [${iconNode(x).map(swiftNode).join(", ")}]`).join("\n")}
        }
    }
}
`;

if (check) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== swift) {
    console.error(`${out} is out of date: run pnpm icons:gen`);
    process.exit(1);
  }
} else {
  writeFileSync(out, swift);
  console.log(`wrote ${out} (${names.length} icons, lucide-react ${version})`);
}
